const assert=require('node:assert/strict');
const model=require('../assets/oa-map-model.js');
function record(id,department,lat=40,extra={}){return {id,institution:'Official University',institutionKey:'Official University',school:'Business School',department,lat,lng:-80,address:id+' office',rowIds:[id],...extra};}
function points(records){return records.flatMap(r=>model.pointsFor({id:'university-'+r.id,institution:r.institutionKey,schools:[{name:r.school,rows:[{id:r.id,department:r.department,n:2}]}]}, {verified:records,locations:new Map(),historic:new Map(),rowInstitutions:{}}));}
function merge(records){return model.mergeSchoolLocations(model.consolidatePoints(points(records),records),records);}
const records=[record('operations','Operations'),record('information','Information Systems',40.0005),record('school','',40.0007)];
const result=merge(records),p=result[0];
assert.equal(result.length,1);
assert.equal(p.card.schools[0].rows.length,3);
assert.equal(p.lat,40.0007,'school-level verified record supplies the representative point');
assert.equal(p.address,'school office');
assert.equal(p.card.n,6);
assert.equal(p.sourceUniversityIds.length,3);
assert.equal(p.sourceCardIds.length,3);
assert.deepEqual(p.sourceEvidenceIds.slice().sort(),['information','operations','school']);
assert.equal(p.locationSources.find(r=>r.id==='operations').lat,40,'original office coordinates survive shared marker');
assert.equal(p.card.schools[0].rows.find(r=>r.department==='Operations').locationSources[0].address,'operations office');
assert.ok(model.pointMatchScore(p,'Official University','Business School','Operations')>0);
assert.ok(model.pointMatchScore(p,'Official University','Business School','Information Systems')>0);
assert.equal(model.pointMatchScore(p,'Official University','Business School','Unknown'),0);
assert.equal(merge(records.slice().reverse())[0].card.id,p.card.id,'representative and card ID are input-order independent');
assert.equal(model.mergeSchoolLocations(points(records).concat(points(records)),records)[0].card.n,6,'source rows counted once');
assert.equal(merge([record('a','Operations'),record('b','Information',40.01)]).length,2,'distant campuses remain separate');
assert.equal(merge([record('a','Operations'),record('b','Information',40,{school:'Engineering'})]).length,2,'different schools remain separate');
assert.equal(merge([record('a','Operations',40,{school:''}),record('b','Information',40,{school:''})]).length,2,'empty school cannot absorb distinct departments');
assert.equal(merge([record('a','Operations',40,{school:''})])[0].locationSources[0].id,'a','unmerged departments retain location provenance too');
assert.equal(merge([record('a','Operations'),record('b','Information',40,{institution:'Other University',institutionKey:'Other University'})]).length,2,'nearby unrelated universities remain separate');
assert.equal(merge([record('a','Operations'),record('b','Information',40.001),record('c','Finance',40.002)]).length,2,'complete-link prevents a proximity chain from merging distant endpoints');
const overrides=[record('a','Operations',40,{mapCardIdentity:'campus-one',mapCardLabel:'Named campus',mapCardSchool:'Business'}),record('b','Information',40.01,{mapCardIdentity:'campus-one',mapCardLabel:'Named campus',mapCardSchool:'Business'})];
assert.equal(merge(overrides).length,1,'reviewed explicit identity overrides distance');
assert.equal(merge(overrides)[0].label,'Named campus');
assert.equal(merge(overrides)[0].card.schools[0].name,'Business');
assert.equal(merge([overrides[0],{...overrides[1],lat:40,mapCardIdentity:'campus-two'}]).length,2,'different explicit identities remain separate');
const edited=points(records);edited[0].card.schools[0].rows[0].locationEdited=true;
assert.equal(model.mergeSchoolLocations(edited,records).length,2,'edited school/department remains independent');
const aliasRecords=[record('primary','Operations',40,{locationIdentity:'primary'}),record('secondary','Operations',40.0001,{locationIdentity:'primary'})];
const aliasMerged=model.mergeSchoolLocations(model.consolidatePoints(points(aliasRecords),aliasRecords),aliasRecords)[0];
assert.equal(aliasMerged.sourceUniversityIds.length,2,'university provenance survives both layers');
assert.equal(aliasMerged.locationSources.length,2,'every alias retains its original location evidence');
const grouped=records.map(r=>({...r,locationGroup:r.id==='information'?'other-call':'two-campuses'}));
const groupPoint=merge(grouped)[0];
assert.deepEqual(model.locationGroupsForTarget(groupPoint,'Official University','Business School','Information Systems',grouped),['other-call']);
assert.deepEqual(model.locationGroupsForTarget(groupPoint,'Official University','Business School','Operations',grouped),['two-campuses']);
assert.deepEqual(model.locationGroupsForTarget(groupPoint,'Unrelated','Business School','Operations',grouped),[]);
const legacy=points([record('legacy','History',40.0001)])[0];
legacy.locationVerified=false;legacy.sourceEvidenceIds=[];legacy.approximate=true;
legacy.card.schools[0].rows[0].mapSources[0].evidenceId=null;
const mixed=model.mergeSchoolLocations([legacy,...points(records)],records)[0];
assert.equal(mixed.address,'school office','verified school office wins over legacy anchor');
assert.equal(mixed.containsApproximateLocations,true);
assert.equal(mixed.locationSources.find(s=>s.locationVerified===false).approximate,true,'legacy uncertainty survives');
assert.equal(mixed.card.schools[0].rows.find(r=>r.department==='History').locationSources.length,1);
const schoolAliases={schoolAliases:[{institution:'Official University',aliases:['Business School','Old Business'],school:'Official Business School'}]};
const naming=[record('a','Operations'),record('b','Information',40.0001,{school:'Old Business'})];
const named=model.mergeSchoolLocations(points(naming),naming,schoolAliases);
assert.equal(named.length,1);
assert.equal(named[0].school,'Official Business School');
assert.ok(model.pointMatchScore(named[0],'Official University','Old Business','Information')>0,'canonical school retains legacy school links');
assert.ok(model.pointMatchScore(named[0],'Official University','Official Business School','Information')>0,'canonical school name also opens its original department');
const unrelated=naming.map(r=>({...r,institution:'Unrelated',institutionKey:'Unrelated'}));
assert.equal(model.mergeSchoolLocations(points(unrelated),unrelated,schoolAliases).length,2,'school aliases apply only within their named institution');
const generic=[record('main','',40,{school:'',mapCardIdentity:'main'}),record('engineering','',40,{school:'Engineering',mapCardIdentity:'main'})];
const main=merge(generic)[0];
assert.equal(main.card.schools.length,1);
assert.equal(main.card.schools[0].name,'Engineering');
assert.equal(main.card.schools[0].rows.length,1,'generic university source is absorbed into the sole named school listing');
assert.equal(main.card.schools[0].rows[0].mapSources.length,2);
assert.ok(model.pointMatchScore(main,'Official University','','')>0);
const distinct=[record('business','Operations',40,{mapCardIdentity:'shared'}),record('engineering','Operations',40,{school:'Engineering',mapCardIdentity:'shared'})];
assert.equal(merge(distinct)[0].card.schools.length,2,'explicit shared location retains meaningful different school sections');
const mutable=[record('mutable','Operations')];
assert.equal(points(mutable)[0].lat,40);
mutable[0].lat=41;
assert.equal(points(mutable)[0].lat,41,'verified index retains current record values');
mutable[0]={...mutable[0],lat:42};
assert.equal(points(mutable)[0].lat,42,'verified index detects replacement record objects with unchanged keys');
mutable[0].rowIds=['moved'];
assert.equal(points(mutable)[0].locationVerified,undefined,'index invalidates when an existing record changes row membership');
mutable[0].rowIds=['mutable'];mutable[0].institutionKey='Another Institution';
assert.equal(points(mutable)[0].lat,42,'index invalidates changed institution keys and preserves alias matching');
console.log('Physical school-card proximity, overrides, representative, provenance, edits and deep-link tests passed.');

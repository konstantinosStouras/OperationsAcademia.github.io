const assert = require('node:assert/strict');
const D = require('../assets/oa-advert-dup.js');
const jobs = require('../data/jobs.json');
const ohio = jobs.find(r => r.id === '2027-ohio-state-university-20261019');
const bellarmine = jobs.find(r => r.id === '2027-bellarmine-university-20260718');
assert(ohio && bellarmine);
const copy = {id:'sheet-ohio',year:2027,institution:'The Ohio State University',unit:'Optimization for Machine Learning',department:'Optimization for Machine Learning',levels:['Assistant Professor'],adUrl:'https://apply.interfolio.com/195349'};
assert.equal(D.advertRepeat(copy,[ohio]).id,ohio.id);
assert.equal(D.advertRepeat({...copy,adUrl:'https://dossier.interfolio.com/apply/195349?utm_source=sheet'},[ohio]).id,ohio.id);
assert.equal(D.advertRepeat({...copy,adUrl:'https://apply.interfolio.com/195056'},[ohio]),null);
const bell = {id:'sheet-bell',year:2027,institution:'Bellarmine University',unit:'Information Systems and Artificial Intelligence',levels:['Assistant Professor','Other Ranks'],adUrl:'https://www.higheredjobs.com/faculty/details.cfm?JobCode=179597757&Title=New+title'};
assert.equal(D.advertRepeat(bell,[bellarmine]).id,bellarmine.id);
assert.equal(D.advertRepeat({...bell,adUrl:bell.adUrl.replace('179597757','179597758')},[bellarmine]),null);
assert.equal(D.advertRepeat({...bell,year:2028},[bellarmine]),null);
assert.equal(D.advertRepeat({...bell,institution:'Boston University'},[bellarmine]),null);
const generic = {...copy,adUrl:'https://example.edu/careers',postedAtUrl:'https://example.edu/apply',unit:'Supply Chain'};
assert.equal(D.advertRepeat({...generic,id:'other',unit:'Information Systems'},[generic]),null);
const conflict = {...copy,id:'other',adUrl:'https://www.higheredjobs.com/faculty/details.cfm?JobCode=111',postedAtUrl:copy.adUrl};
assert.equal(D.advertRepeat({...conflict,id:'third',adUrl:conflict.adUrl.replace('111','112')},[conflict]),null);
const swept = D.findAdvertRepeats([copy,bell],jobs);
assert.equal(swept.drop.length,2); assert.equal(swept.keep.length,0);
console.log('Vacancy regressions passed: both queue duplicates suppressed; distinct IDs, universities, seasons and generic-portal vacancies retained.');

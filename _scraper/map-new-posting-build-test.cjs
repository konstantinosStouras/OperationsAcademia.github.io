const assert=require('node:assert/strict');
const routing=require('../assets/oa-map-routing.js');
const model=require('../assets/oa-map-model.js');
(async()=>{
  const {buildDirectory}=await import('./directory-model.mjs');
  const {attachMapLocations,attachDepartmentLinks}=await import('./map-directory.mjs');
  const institution='Routing Test University';
  const archive=[{institution,school:'Business School',department:'BA',facultyUrl:'https://example.edu/business/faculty'}];
  const original=buildDirectory({archive}).rows[0];
  const reviewed={id:'reviewed-analytics',institution,school:'Business School',department:'Department of Information Systems and Analytics',rowIds:[original.id],lat:40,lng:-80};
  const jobs=[{institution,school:'Business School',unit:'Business Analytics',country:'United States',posted:'2026-10-25'}];
  const rows=buildDirectory({archive,jobs}).rows;
  assert.equal(rows.length,1,'a known acronym joins the full department within the same school');
  assert.ok((rows[0].sourceRowIds||[]).includes(original.id),'the deleted acronym row remains in canonical row lineage');
  assert.ok(rows[0].sourceRowAliases.some(alias=>alias.school==='Business School'&&alias.department==='BA'),'the former display name remains available to old links');
  assert.equal(rows[0].facultyUrl,archive[0].facultyUrl,'a new posting cannot erase the existing faculty link');
  attachMapLocations(rows,[reviewed]);
  attachDepartmentLinks(rows,[reviewed]);
  assert.equal(rows[0].mapLocationKind,'exact','a canonical row-ID change preserves existing reviewed department evidence');
  assert.deepEqual(rows[0].mapLocationIds,[reviewed.id]);
  assert.equal(rows[0].facultyUrl,archive[0].facultyUrl);
  const resolver=routing.createResolver({verified:[reviewed],directory:rows});
  assert.deepEqual(resolver.resolve({institution,school:'Business School',department:'BA'}),{ids:[reviewed.id],kind:'department'},'a future old-name posting still resolves the reviewed department');
  const data={verified:[reviewed],directory:rows,locations:new Map(),historic:new Map(),rowInstitutions:{}};
  const point=model.pointsFor({id:'routing-university',institution,schools:[{name:'Business School',rows}]},data)[0];
  assert.ok(model.pointMatchScore(point,institution,'Business School','BA')>0,'the old BA job link still selects the reviewed department card');
  const separated=buildDirectory({archive,jobs:[{institution,school:'Engineering School',unit:'Business Analytics'}]}).rows;
  assert.equal(separated.length,2,'an acronym in an explicit business school cannot migrate into engineering');
  assert.ok(separated.some(row=>row.school==='Business School'&&row.facultyUrl===archive[0].facultyUrl));
  const oldSchoolless=buildDirectory({jobs:[{institution,unit:'Business Analytics'}]}).rows[0];
  const schooled=buildDirectory({jobs:[{institution,unit:'Business Analytics'},{institution,school:'Business School',unit:'Business Analytics'}]}).rows;
  assert.equal(schooled.length,1);
  assert.ok((schooled[0].sourceRowIds||[]).includes(oldSchoolless.id),'school-less canonical merges retain original row lineage too');
  assert.ok(schooled[0].sourceRowAliases.some(alias=>alias.school===''&&alias.department==='Business Analytics'),'school-less source names survive the merge');
  const repeated=buildDirectory({archive,jobs}).rows;
  attachMapLocations(repeated,[reviewed]);attachDepartmentLinks(repeated,[reviewed]);
  assert.deepEqual(repeated,rows,'a new-posting rebuild is reproducible');
  console.log('New-posting builds retain verified row lineage, curated links and school boundaries.');
})().catch(error=>{console.error(error);process.exitCode=1;});
